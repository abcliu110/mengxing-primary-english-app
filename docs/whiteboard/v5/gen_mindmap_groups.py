def field(w, k):
    if k == 'p': return w['pos']
    if k == 'm': return w['meaning']
    if k == 's': return ((w.get('senses') or [{}])[0].get('scene') or '')

def main():
    db = load_db(); subs = {}
    for w in db: subs.setdefault(w['theme_sub'], []).append(w)
    out, review = [], []
    assert set(subs) == set(R), set(subs) ^ set(R)
    for sub, ws in subs.items():
        nodes = ws[:18][:16]   # 与旧导图 drawThemeMindMap 画出的节点完全一致
        groups = [{'name': n, 'ids': [], 'rule': c} for n, c in R[sub]] + [{'name': '更多', 'ids': [], 'rule': None}]
        for w in nodes:
            g = next(g for g in groups if g['rule'] is None or all(re.search(rx, field(w, k)) for k, rx in g['rule'].items()))
            g['ids'].append(w['id'])
            review.append(f"{sub}\t{g['name']}\t{w['word']}\t{w['pos']}\t{w['meaning']}\t{('依据 ' + ' & '.join(f'{k}~/{v}/' for k, v in g['rule'].items())) if g['rule'] else '规则分不出'}")
        empty = [g['name'] for g in groups if not g['ids'] and g['rule'] is not None]
        assert not empty, (sub, '空组', empty)
        assert all(len(g['ids']) <= 6 for g in groups), (sub, '一组最多 6 个叶子')
        out.append({'sub': sub, 'idx': len(out), 'total': len(ws), 'nodes': [w['id'] for w in nodes],
                    # 展示顺序：ORDER 里有就按 ORDER，否则按规则顺序（规则顺序是为了先中先得，不一定适合讲解）；「更多」永远最后
                    'groups': sorted([{'name': g['name'], 'ids': g['ids'], 'rule': g['rule']} for g in groups if g['ids']],
                                     key=lambda g: (g['rule'] is None, ORDER.get(sub, [x for x, _ in R[sub]]).index(g['name']) if g['rule'] else 0))})
    OUT.write_text(json.dumps({'_说明': '主题思维导图讲解幕语义分组表（v5/gen_mindmap_groups.py 生成，按 pos / meaning / senses[0].scene 规则分组；规则分不出的放「更多」）。idx = App 里 VOCAB_DB 子主题首次出现顺序 = 页签 hd_mindmap 的幕序号。',
                               'subs': out}, ensure_ascii=False, indent=1), encoding='utf-8')
    for o in out: print(o['idx'] + 1, o['sub'], ' / '.join(f"{g['name']}{len(g['ids'])}" for g in o['groups']))
    if '--review' in sys.argv: print('\n'.join(review))

if __name__ == '__main__': main()
